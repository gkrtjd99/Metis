#!/usr/bin/env node
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { DEFAULT_CONFIG } from "../src/core/config.js";
import { capabilityRegistryManifest } from "../src/core/capabilities.js";
import {
  CHECKPOINT_KINDS,
  CLEANUP_SCOPES,
  CONFIG_VERSION,
  PHASES,
  REQUIREMENT_KINDS,
  ROLES,
  RUNTIME_LAYOUT_VERSION,
  SCHEMA_VERSION,
  SPECIALIST_CAPABILITIES,
  TASK_KINDS
} from "../src/core/metadata.js";
import { RUNTIME_AREAS } from "../src/core/paths.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const output = path.join(root, "docs", "REFERENCE.md");
const packageJson = JSON.parse(readFileSync(path.join(root, "package.json"), "utf8"));

function sorted(value) {
  if (Array.isArray(value)) return value.map(sorted);
  if (value && typeof value === "object") {
    return Object.fromEntries(Object.entries(value).sort(([left], [right]) => left.localeCompare(right)).map(([key, item]) => [key, sorted(item)]));
  }
  return value;
}

function codeList(values) {
  return ["```text", ...values, "```"].join("\n");
}

function runtimeTree() {
  const lines = [".metis/", "├── layout.json", "├── config.json"];
  const entries = Object.entries(RUNTIME_AREAS);
  entries.forEach(([name, descriptor], index) => {
    const terminal = index === entries.length - 1;
    const suffix = name === "state" ? "/" : "/";
    lines.push(`${terminal ? "└──" : "├──"} ${descriptor.relative}${suffix}  ${descriptor.class}: ${descriptor.description}`);
    if (name === "state") lines.push(`${terminal ? "    " : "│   "}└── state.db`);
  });
  return ["```text", ...lines, "```"].join("\n");
}

function capabilityTable() {
  const rows = ["| Capability | Review role | Capability document |", "| --- | --- | --- |"];
  for (const item of capabilityRegistryManifest()) {
    rows.push(`| \`${item.name}\` | ${item.reviewRole ? `\`${item.reviewRole}\`` : "none"} | \`${item.skillPath}\` |`);
  }
  return rows.join("\n");
}

const cliHelp = execFileSync(process.execPath, ["--no-warnings", "src/cli.js", "--help"], {
  cwd: root,
  encoding: "utf8",
  env: { ...process.env, NODE_NO_WARNINGS: "1" }
}).trim();

const content = `# Generated Reference

Do not edit this file by hand.
Run \`npm run docs:generate\` after changing runtime metadata, defaults, layout, or CLI help.

## Release metadata

\`\`\`json
${JSON.stringify({
  name: packageJson.name,
  version: packageJson.version,
  schemaVersion: SCHEMA_VERSION,
  configVersion: CONFIG_VERSION,
  runtimeLayoutVersion: RUNTIME_LAYOUT_VERSION
}, null, 2)}
\`\`\`

## Canonical phases

${codeList(PHASES)}

## Canonical roles

${codeList(ROLES)}

## Canonical task kinds

${codeList(TASK_KINDS)}

## Specialist capabilities

${codeList(SPECIALIST_CAPABILITIES)}

## Capability registry

${capabilityTable()}

## Requirement kinds

${codeList(REQUIREMENT_KINDS)}

## Checkpoint kinds

${codeList(CHECKPOINT_KINDS)}

## Cleanup scopes

${codeList(CLEANUP_SCOPES)}

Cleanup preview:

\`\`\`sh
metis clean --scope cache --dry-run --pretty
\`\`\`

Cleanup apply:

\`\`\`sh
metis clean --scope cache --pretty
\`\`\`

There is no \`--apply\` flag.

## Runtime layout

${runtimeTree()}

Canonical database path:

\`\`\`text
.metis/state/state.db
\`\`\`

## Default configuration

\`\`\`json
${JSON.stringify(sorted(DEFAULT_CONFIG), null, 2)}
\`\`\`

## CLI help

\`\`\`text
${cliHelp}
\`\`\`
`;

if (process.argv.includes("--check")) {
  const current = readFileSync(output, "utf8");
  if (current !== content) {
    console.error("docs/REFERENCE.md is stale. Run `npm run docs:generate`.");
    process.exitCode = 1;
  }
} else {
  writeFileSync(output, content, "utf8");
  console.log(`Wrote ${path.relative(root, output)}.`);
}
