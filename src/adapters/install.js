function sha256Buffer(value) {
  return createHash("sha256").update(value).digest("hex");
}

function assertGitProjectRoot(projectRoot) {
  try {
    execFileSync("git", ["rev-parse", "--show-toplevel"], {
      cwd: projectRoot,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"]
    });
  } catch {
    invariant(false, "GIT_REQUIRED", "Metis host attachment requires a Git project root.");
  }
}

function fileHash(file) {
  return sha256Buffer(readFileSync(file));
}

function manifestPath(projectRoot) {
  return safeManifestPath(projectRoot, ".agents/metis/install-manifest.json", { code: "INSTALL_MANIFEST_PATH_INVALID" }).absolute;
}

function relativeToProject(projectRoot, target) {
  return path.relative(projectRoot, target).replaceAll(path.sep, "/");
}

function managedPath(projectRoot, relative, code = "MANIFEST_PATH_INVALID") {
  return safeManifestPath(projectRoot, relative, { code });
}

function validateManifest(projectRoot, manifest) {
  invariant(manifest && typeof manifest === "object" && !Array.isArray(manifest), "INSTALL_MANIFEST_INVALID", "The install manifest must be an object.");
  invariant(Array.isArray(manifest.hosts), "INSTALL_MANIFEST_INVALID", "The install manifest hosts must be an array.");
  invariant(Array.isArray(manifest.files), "INSTALL_MANIFEST_INVALID", "The install manifest files must be an array.");
  for (const record of manifest.files) {
    invariant(record && typeof record === "object", "INSTALL_MANIFEST_INVALID", "Each install manifest file record must be an object.");
    managedPath(projectRoot, record.path);
    if (record.backupPath) managedPath(projectRoot, record.backupPath);
    for (const backupPath of record.recoveryBackups ?? []) managedPath(projectRoot, backupPath);
  }
  if (manifest.marketplace?.path) managedPath(projectRoot, manifest.marketplace.path);
  if (manifest.ignore?.file) managedPath(projectRoot, manifest.ignore.file);
  return manifest;
}

function readManifest(projectRoot) {
  const file = manifestPath(projectRoot);
  if (!existsSync(file)) return null;
  const manifest = JSON.parse(readFileSync(file, "utf8"));
  invariant(
    manifest.version === INSTALL_MANIFEST_VERSION,
    "INSTALL_MANIFEST_VERSION",
    "This installation was created by an incompatible Metis version. Remove it before installing this release."
  );
  return validateManifest(projectRoot, manifest);
}

function newManifest(existing = null) {
  return existing ?? {
    version: INSTALL_MANIFEST_VERSION,
    installationId: randomUUID(),
    hosts: [],
    files: [],
    marketplace: null,
    ignore: { file: null, entries: [] },
    createdAt: new Date().toISOString(),
    updatedAt: new Date().toISOString()
  };
}

function writeManifest(projectRoot, manifest) {
  validateManifest(projectRoot, manifest);
  manifest.updatedAt = new Date().toISOString();
  const file = manifestPath(projectRoot);
  mkdirSync(path.dirname(file), { recursive: true });
  writeFileSync(file, `${stableStringify(manifest)}\n`, "utf8");
  return relativeToProject(projectRoot, file);
}

function recordFor(manifest, relative) {
  return manifest.files.find((item) => item.path === relative) ?? null;
}

function backupExisting(projectRoot, target, relative, manifest, label = "original") {
  const safeRelative = managedPath(projectRoot, relative, "INSTALL_PATH_INVALID").relative;
  const backupRelative = `.metis/backups/install/${manifest.installationId}/${label}/${safeRelative}`;
  const backup = managedPath(projectRoot, backupRelative, "INSTALL_BACKUP_PATH_INVALID").absolute;
  mkdirSync(path.dirname(backup), { recursive: true });
  copyFileSync(target, backup);
  return backupRelative;
}

function setManagedFile(projectRoot, relative, content, hosts, options, manifest) {
  const safeTarget = managedPath(projectRoot, relative, "INSTALL_PATH_INVALID");
  relative = safeTarget.relative;
  const target = safeTarget.absolute;
  const expected = Buffer.isBuffer(content) ? content : Buffer.from(String(content), "utf8");
  const installedSha256 = sha256Buffer(expected);
  const existingRecord = recordFor(manifest, relative);
  const currentExists = existsSync(target);
  if (currentExists && !lstatSync(target).isFile()) {
    return { path: relative, status: "conflict", reason: "target is not a regular file" };
  }
  const currentHash = currentExists ? fileHash(target) : null;
  const sourceEqualsTarget = options.sourcePath && path.resolve(options.sourcePath) === path.resolve(target);
  if (sourceEqualsTarget) {
    const record = existingRecord ?? {
      path: relative,
      hosts: [],
      installedSha256: currentHash,
      managed: true,
      created: false,
      backupPath: null,
      recoveryBackups: [],
      mode: options.mode ?? null
    };
    record.hosts = [...new Set([...record.hosts, ...hosts])].sort();
    record.installedSha256 = currentHash;
    if (!existingRecord) manifest.files.push(record);
    return { path: relative, status: "current", sha256: currentHash };
  }
  if (currentExists && currentHash === installedSha256) {
    const record = existingRecord ?? {
      path: relative,
      hosts: [],
      installedSha256,
      managed: false,
      created: false,
      backupPath: null,
      recoveryBackups: [],
      mode: options.mode ?? null
    };
    record.hosts = [...new Set([...record.hosts, ...hosts])].sort();
    record.installedSha256 = installedSha256;
    if (!existingRecord) manifest.files.push(record);
    return { path: relative, status: existingRecord ? "current" : "adopted", sha256: installedSha256 };
  }
  const safelyOwned = Boolean(existingRecord?.managed && currentHash === existingRecord.installedSha256);
  if (currentExists && !safelyOwned && !options.force) {
    return { path: relative, status: "preserved", reason: "existing file differs; use --force to replace it" };
  }
  let record = existingRecord;
  if (!record) {
    record = {
      path: relative,
      hosts: [],
      installedSha256: null,
      managed: true,
      created: !currentExists,
      backupPath: null,
      recoveryBackups: [],
      mode: options.mode ?? null
    };
    manifest.files.push(record);
  }
  if (currentExists && !safelyOwned) {
    if (!record.backupPath) record.backupPath = backupExisting(projectRoot, target, relative, manifest, "original");
    else record.recoveryBackups.push(backupExisting(projectRoot, target, relative, manifest, `modified-${Date.now()}`));
  }
  mkdirSync(path.dirname(target), { recursive: true });
  writeFileSync(target, expected, options.mode ? { mode: options.mode } : undefined);
  record.hosts = [...new Set([...record.hosts, ...hosts])].sort();
  record.installedSha256 = installedSha256;
  record.managed = true;
  record.mode = options.mode ?? record.mode ?? null;
  return { path: relative, status: currentExists ? "updated" : "created", sha256: installedSha256 };
}

function copyManagedFile(projectRoot, source, relative, hosts, options, manifest) {
  return setManagedFile(projectRoot, relative, readFileSync(source), hosts, { ...options, sourcePath: source }, manifest);
}

function walkFiles(root, relative = "") {
  const output = [];
  if (!existsSync(root)) return output;
  for (const entry of readdirSync(path.join(root, relative), { withFileTypes: true })) {
    const child = path.join(relative, entry.name);
    if (entry.isDirectory()) output.push(...walkFiles(root, child));
    else if (entry.isFile()) output.push(child);
  }
  return output.sort();
}

function copyTree(projectRoot, sourceRoot, targetRelative, hosts, options, manifest) {
  return walkFiles(sourceRoot).map((relative) => copyManagedFile(
    projectRoot,
    path.join(sourceRoot, relative),
    path.posix.join(targetRelative, relative.replaceAll(path.sep, "/")),
    hosts,
    options,
    manifest
  ));
}

function installedSkillText(projectRoot, skillName = "metis") {
  const source = readFileSync(path.join(packageRoot, "skills", skillName, "SKILL.md"), "utf8");
  const launcher = path.join(projectRoot, ".agents", "metis", "metis.mjs").replaceAll("\\", "/");
  return source
    .replace("node --no-warnings <skill-directory>/scripts/metis.mjs", `node --no-warnings "${launcher}"`)
    .replace("node --no-warnings <skill-directory>/../metis/scripts/metis.mjs", `node --no-warnings "${launcher}"`);
}

function installSkill(projectRoot, targetRelative, hosts, options, manifest, skillName = "metis") {
  const results = [setManagedFile(projectRoot, path.posix.join(targetRelative, "SKILL.md"), installedSkillText(projectRoot, skillName), hosts, options, manifest)];
  for (const directory of ["references", "agents", "capabilities"]) {
    results.push(...copyTree(projectRoot, path.join(packageRoot, "skills", skillName, directory), path.posix.join(targetRelative, directory), hosts, options, manifest));
  }
  return results;
}

function installRuntime(projectRoot, options, manifest) {
  const target = ".agents/metis/runtime";
  const results = [];
  for (const directory of ["src", "skills", "commands", "agents", "adapters", ".codex-plugin", ".claude-plugin"]) {
    results.push(...copyTree(projectRoot, path.join(packageRoot, directory), path.posix.join(target, directory), ["common"], options, manifest));
  }
  const browserVerifier = path.join(packageRoot, "scripts", "chromium-browser-verifier.mjs");
  results.push(copyManagedFile(
    projectRoot,
    browserVerifier,
    path.posix.join(target, "scripts", "chromium-browser-verifier.mjs"),
    ["common"],
    { ...options, mode: 0o755 },
    manifest
  ));
  for (const file of ["LICENSE", "plugin.json"]) {
    const source = path.join(packageRoot, file);
    if (existsSync(source)) results.push(copyManagedFile(projectRoot, source, path.posix.join(target, file), ["common"], options, manifest));
  }
  results.push(setManagedFile(projectRoot, path.posix.join(target, "package.json"), `${JSON.stringify({
    name: "metis-runtime",
    version: PACKAGE_VERSION,
    private: true,
    type: "module",
    engines: { node: ">=22.16.0" }
  }, null, 2)}\n`, ["common"], options, manifest));
  const launcher = `#!/usr/bin/env -S node --no-warnings\nimport { main } from "./runtime/src/cli.js";\nprocess.exitCode = await main();\n`;
  results.push(setManagedFile(projectRoot, ".agents/metis/metis.mjs", launcher, ["common"], { ...options, mode: 0o755 }, manifest));
  return { target, launcher: ".agents/metis/metis.mjs", results };
}

