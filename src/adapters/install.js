function localIgnoreFile(projectRoot) {
  const gitDirectory = path.join(projectRoot, ".git");
  if (existsSync(gitDirectory) && lstatSync(gitDirectory).isDirectory()) {
    return managedPath(projectRoot, ".git/info/exclude", "INSTALL_IGNORE_PATH_INVALID").absolute;
  }
  return managedPath(projectRoot, ".gitignore", "INSTALL_IGNORE_PATH_INVALID").absolute;
}

function ignoreEntries(selected) {
  const entries = [
    { line: "/.metis/", hosts: ["common"] },
    { line: "/.agents/metis/", hosts: ["common"] }
  ];
  if (selected.includes("codex")) entries.push(
    { line: "/.agents/skills/metis/", hosts: ["codex"] },
    { line: "/.agents/plugins/marketplace.json", hosts: ["codex"] },
    { line: "/plugins/metis/", hosts: ["codex"] },
    { line: "/.codex/config.toml", hosts: ["codex"] },
    { line: "/.codex/agents/metis-*.toml", hosts: ["codex"] }
  );
  if (selected.includes("claude")) entries.push(
    { line: "/.claude/commands/metis.md", hosts: ["claude"] },
    { line: "/.claude/skills/metis/", hosts: ["claude"] },
    { line: "/.claude/agents/metis-*.md", hosts: ["claude"] }
  );
  if (selected.includes("opencode")) entries.push(
    { line: "/.opencode/commands/metis.md", hosts: ["opencode"] },
    { line: "/.opencode/skills/metis/", hosts: ["opencode"] },
    { line: "/.opencode/agents/metis-*.md", hosts: ["opencode"] }
  );
  return entries;
}

function ensureIgnoreEntries(projectRoot, selected, manifest) {
  const file = localIgnoreFile(projectRoot);
  mkdirSync(path.dirname(file), { recursive: true });
  const original = existsSync(file) ? readFileSync(file, "utf8") : "";
  const lines = new Set(original.split(/\r?\n/u));
  const additions = [];
  for (const entry of ignoreEntries(selected)) {
    const existing = manifest.ignore.entries.find((item) => item.line === entry.line);
    if (existing) existing.hosts = [...new Set([...existing.hosts, ...entry.hosts])].sort();
    else manifest.ignore.entries.push({ ...entry, added: !lines.has(entry.line) });
    if (!lines.has(entry.line)) {
      additions.push(entry.line);
      lines.add(entry.line);
    }
  }
  if (additions.length > 0) {
    const prefix = original && !original.endsWith("\n") ? "\n" : "";
    writeFileSync(file, `${original}${prefix}${additions.join("\n")}\n`, "utf8");
  }
  manifest.ignore.file = relativeToProject(projectRoot, file);
  return { file: manifest.ignore.file, added: additions };
}

function removeExactLines(file, lines, dryRun) {
  if (!existsSync(file) || lines.length === 0) return [];
  const remove = new Set(lines);
  const original = readFileSync(file, "utf8");
  const removed = original.split(/\r?\n/u).filter((line) => remove.has(line));
  if (dryRun || removed.length === 0) return removed;
  let next = original.split(/\r?\n/u).filter((line) => !remove.has(line)).join("\n").replace(/\n{3,}/gu, "\n\n");
  if (next && !next.endsWith("\n")) next += "\n";
  if (!next.trim()) rmSync(file, { force: true });
  else writeFileSync(file, next, "utf8");
  return removed;
}

function pruneEmptyParents(projectRoot, target) {
  let current = path.dirname(target);
  const root = path.resolve(projectRoot);
  while (path.resolve(current).startsWith(`${root}${path.sep}`)) {
    try {
      if (readdirSync(current).length > 0) break;
      rmSync(current, { recursive: true, force: true });
    } catch { break; }
    current = path.dirname(current);
  }
}

export function installAdapters(projectRoot, hosts, force = false) {
  assertGitProjectRoot(projectRoot);
  ensureRuntimeLayout(projectRoot);
  const selected = hosts.includes("all") ? ["codex", "claude", "opencode"] : [...new Set(hosts)];
  invariant(selected.length > 0, "HOST_REQUIRED", "Select at least one host.");
  for (const host of selected) invariant(["codex", "claude", "opencode"].includes(host), "HOST_INVALID", `Unsupported host: ${host}.`);
  const existingManifest = readManifest(projectRoot);
  const manifest = newManifest(existingManifest);
  const previousManifestState = existingManifest ? stableStringify({ ...existingManifest, updatedAt: undefined }) : null;
  const options = { force: Boolean(force) };
  const runtime = installRuntime(projectRoot, options, manifest);
  const installed = {};
  if (selected.includes("codex")) installed.codex = installCodex(projectRoot, options, manifest);
  if (selected.includes("claude")) installed.claude = installClaude(projectRoot, options, manifest);
  if (selected.includes("opencode")) installed.opencode = installOpenCode(projectRoot, options, manifest);
  manifest.hosts = [...new Set([...manifest.hosts, ...selected])].sort();
  const ignore = ensureIgnoreEntries(projectRoot, selected, manifest);
  const results = [
    ...runtime.results,
    ...Object.values(installed).flatMap((value) => value.results ?? [])
  ];
  const manifestStateChanged = !existingManifest
    || previousManifestState !== stableStringify({ ...manifest, updatedAt: undefined })
    || results.some((item) => ["created", "updated"].includes(item.status))
    || ignore.added.length > 0
    || Object.values(installed).some((value) => ["created", "updated"].includes(value.marketplace?.status));
  const manifestFile = manifestStateChanged
    ? writeManifest(projectRoot, manifest)
    : relativeToProject(projectRoot, manifestPath(projectRoot));
  return {
    runtime: {
      target: path.join(projectRoot, runtime.target),
      targetRelative: runtime.target,
      launcher: path.join(projectRoot, runtime.launcher),
      launcherRelative: runtime.launcher
    },
    installed,
    ignore,
    stateIgnore: managedPath(projectRoot, ignore.file, "INSTALL_IGNORE_PATH_INVALID").absolute,
    manifest: manifestFile,
    created: results.filter((item) => item.status === "created").map((item) => item.path),
    updated: results.filter((item) => item.status === "updated").map((item) => item.path),
    preserved: results.filter((item) => item.status === "preserved"),
    conflicts: results.filter((item) => item.status === "conflict")
  };
}

function sameJson(a, b) {
  return stableStringify(a) === stableStringify(b);
}

function uninstallMarketplace(projectRoot, manifest, options) {
  if (!manifest.marketplace) return { status: "absent" };
  const file = managedPath(projectRoot, manifest.marketplace.path, "INSTALL_MARKETPLACE_PATH_INVALID").absolute;
  if (!existsSync(file)) return { status: "missing" };
  let marketplace;
  try { marketplace = JSON.parse(readFileSync(file, "utf8")); }
  catch { return { status: "conflict", reason: "marketplace file is invalid JSON" }; }
  marketplace.plugins = Array.isArray(marketplace.plugins) ? marketplace.plugins : [];
  const index = marketplace.plugins.findIndex((item) => item?.name === "metis");
  const current = index >= 0 ? marketplace.plugins[index] : null;
  if (current && !sameJson(current, manifest.marketplace.installedEntry) && !options.forceModified) {
    return { status: "conflict", reason: "marketplace entry changed after installation" };
  }
  if (options.dryRun) return { status: "would-remove" };
  if (index >= 0) {
    if (manifest.marketplace.previousEntry) marketplace.plugins[index] = manifest.marketplace.previousEntry;
    else marketplace.plugins.splice(index, 1);
  }
  if (manifest.marketplace.fileCreated && marketplace.plugins.length === 0) {
    rmSync(file, { force: true });
    pruneEmptyParents(projectRoot, file);
  } else {
    writeFileSync(file, `${stableStringify(marketplace)}\n`, "utf8");
  }
  return { status: "removed" };
}

function uninstallBackupPath(projectRoot, options, relative) {
  const id = String(options.uninstallId ?? `uninstall-${Date.now()}`).replace(/[^A-Za-z0-9._-]/gu, "-");
  const safeRelative = managedPath(projectRoot, relative, "INSTALL_PATH_INVALID").relative;
  const backupRelative = `.metis/backups/uninstall/${id}/${safeRelative}`;
  const backup = managedPath(projectRoot, backupRelative, "INSTALL_BACKUP_PATH_INVALID");
  invariant(backup.absolute.startsWith(`${runtimeArea(projectRoot, "backups")}${path.sep}`), "INSTALL_BACKUP_PATH_INVALID", "The uninstall backup path must remain inside the backup area.");
  return { relative: backup.relative, absolute: backup.absolute };
}

function restoreOrRemoveFile(projectRoot, record, options) {
  const safeTarget = managedPath(projectRoot, record.path, "INSTALL_MANIFEST_PATH_INVALID");
  record.path = safeTarget.relative;
  const target = safeTarget.absolute;
  const exists = existsSync(target);
  if (exists && !lstatSync(target).isFile()) {
    return { path: record.path, status: "conflict", reason: "managed path is not a regular file" };
  }
  const currentHash = exists ? fileHash(target) : null;
  const modified = exists && currentHash !== record.installedSha256;
  let modifiedBackup = null;
  if (modified && !options.forceModified) {
    return { path: record.path, status: "conflict", reason: "file changed after installation", currentSha256: currentHash, installedSha256: record.installedSha256 };
  }
  if (modified && options.forceModified && options.backupModified) {
    modifiedBackup = uninstallBackupPath(projectRoot, options, record.path);
  }
  const action = record.backupPath ? "restore" : record.managed ? "remove" : "preserve";
  if (options.dryRun) {
    return {
      path: record.path,
      status: modifiedBackup ? `would-backup-and-${action}` : `would-${action}`,
      modified,
      ...(modifiedBackup ? { backupPath: modifiedBackup.relative } : {})
    };
  }
  if (modifiedBackup) {
    mkdirSync(path.dirname(modifiedBackup.absolute), { recursive: true });
    copyFileSync(target, modifiedBackup.absolute);
  }
  const safeBackup = record.backupPath ? managedPath(projectRoot, record.backupPath, "INSTALL_MANIFEST_PATH_INVALID") : null;
  if (safeBackup && existsSync(safeBackup.absolute)) {
    mkdirSync(path.dirname(target), { recursive: true });
    copyFileSync(safeBackup.absolute, target);
    return { path: record.path, status: modifiedBackup ? "restored-with-backup" : "restored", modified, ...(modifiedBackup ? { backupPath: modifiedBackup.relative } : {}) };
  }
  if (record.managed && exists) {
    rmSync(target, { force: true });
    pruneEmptyParents(projectRoot, target);
    return { path: record.path, status: modifiedBackup ? "removed-with-backup" : "removed", modified, ...(modifiedBackup ? { backupPath: modifiedBackup.relative } : {}) };
  }
  return { path: record.path, status: record.managed ? "missing" : "preserved", modified, ...(modifiedBackup ? { backupPath: modifiedBackup.relative } : {}) };
}

export function uninstallAdapters(projectRoot, hosts = ["all"], options = {}) {
  const forceModified = Boolean(options.forceModified);
  const effectiveOptions = {
    dryRun: Boolean(options.dryRun),
    forceModified,
    backupModified: forceModified && options.backupModified !== false,
    uninstallId: options.uninstallId ?? `uninstall-${Date.now()}`,
    preflight: options.preflight !== false
  };
  const manifest = readManifest(projectRoot);
  invariant(manifest, "INSTALL_MANIFEST_MISSING", "Metis install manifest is missing. Refusing to guess which files are safe to remove.");
  if (!effectiveOptions.dryRun && effectiveOptions.preflight) {
    const preview = uninstallAdapters(projectRoot, hosts, {
      ...effectiveOptions,
      dryRun: true,
      preflight: false
    });
    if (preview.conflicts.length > 0) return { ...preview, dryRun: false, applied: false, preflight: true };
  }
  options = effectiveOptions;
  if (options.backupModified && !options.dryRun) ensureRuntimeLayout(projectRoot);
  const requested = hosts.includes("all") ? [...manifest.hosts] : [...new Set(hosts)];
  for (const host of requested) invariant(["codex", "claude", "opencode"].includes(host), "HOST_INVALID", `Unsupported host: ${host}.`);
  const desiredRemaining = manifest.hosts.filter((host) => !requested.includes(host));
  const removeCommon = desiredRemaining.length === 0;
  const fileResults = [];
  const retainedRecords = [];
  const failedHosts = new Set();
  for (const record of manifest.files) {
    const targetedHosts = record.hosts.filter((host) => requested.includes(host) || (host === "common" && removeCommon));
    if (targetedHosts.length === 0) {
      retainedRecords.push(record);
      continue;
    }
    const remainingRecordHosts = record.hosts.filter((host) => !targetedHosts.includes(host));
    if (remainingRecordHosts.length > 0) {
      retainedRecords.push({ ...record, hosts: remainingRecordHosts });
      continue;
    }
    const result = restoreOrRemoveFile(projectRoot, record, options);
    fileResults.push(result);
    if (result.status === "conflict") {
      retainedRecords.push(record);
      for (const host of targetedHosts.filter((host) => host !== "common")) failedHosts.add(host);
    }
  }
  let marketplace = { status: "not-requested" };
  if (requested.includes("codex")) {
    marketplace = uninstallMarketplace(projectRoot, manifest, options);
    if (marketplace.status === "conflict") failedHosts.add("codex");
  }
  const successfulHosts = requested.filter((host) => !failedHosts.has(host));
  const effectiveRemaining = [...new Set([
    ...desiredRemaining,
    ...failedHosts
  ])].sort();
  const ignoreToRemove = [];
  for (const entry of manifest.ignore.entries ?? []) {
    const nextHosts = entry.hosts.filter((host) => !successfulHosts.includes(host) && !(host === "common" && effectiveRemaining.length === 0));
    if (nextHosts.length === 0 && entry.added) ignoreToRemove.push(entry.line);
    else entry.hosts = nextHosts;
  }
  manifest.ignore.entries = (manifest.ignore.entries ?? []).filter((entry) => entry.hosts.length > 0);
  const ignoreFile = manifest.ignore.file ? managedPath(projectRoot, manifest.ignore.file, "INSTALL_IGNORE_PATH_INVALID").absolute : localIgnoreFile(projectRoot);
  const ignoreRemoved = removeExactLines(ignoreFile, ignoreToRemove, Boolean(options.dryRun));
  if (!options.dryRun) {
    manifest.files = retainedRecords;
    manifest.hosts = effectiveRemaining;
    if (!effectiveRemaining.includes("codex") && marketplace.status !== "conflict") manifest.marketplace = null;
    if (manifest.hosts.length > 0 || failedHosts.size > 0) writeManifest(projectRoot, manifest);
    else {
      rmSync(manifestPath(projectRoot), { force: true });
      pruneEmptyParents(projectRoot, manifestPath(projectRoot));
    }
  }
  const conflicts = [
    ...fileResults.filter((item) => item.status === "conflict"),
    ...(marketplace.status === "conflict" ? [{ path: manifest.marketplace?.path ?? ".agents/plugins/marketplace.json", ...marketplace }] : [])
  ];
  return {
    requested,
    removedHosts: successfulHosts,
    remainingHosts: effectiveRemaining,
    dryRun: Boolean(options.dryRun),
    applied: !options.dryRun,
    forceModified: Boolean(options.forceModified),
    backupModified: Boolean(options.backupModified),
    uninstallId: options.uninstallId,
    files: fileResults,
    backups: fileResults.filter((item) => item.backupPath).map((item) => ({ path: item.path, backupPath: item.backupPath })),
    conflicts,
    marketplace,
    ignoreRemoved,
    statePreserved: existsSync(path.join(projectRoot, ".metis"))
  };
}

export function installationInventory(projectRoot) {
  const manifest = readManifest(projectRoot);
  if (!manifest) return { installed: false, manifest: null };
  return {
    installed: true,
    manifestPath: relativeToProject(projectRoot, manifestPath(projectRoot)),
    hosts: manifest.hosts,
    files: manifest.files.map((record) => {
      const target = managedPath(projectRoot, record.path, "INSTALL_MANIFEST_PATH_INVALID").absolute;
      const exists = existsSync(target) && lstatSync(target).isFile();
      const currentSha256 = exists ? fileHash(target) : null;
      return {
        path: record.path,
        hosts: record.hosts,
        managed: record.managed,
        state: !exists ? "missing" : currentSha256 === record.installedSha256 ? "current" : "modified",
        installedSha256: record.installedSha256,
        currentSha256,
        backupPath: record.backupPath
      };
    })
  };
}
