function updateMarketplace(projectRoot, options, manifest) {
  const relative = ".agents/plugins/marketplace.json";
  const file = managedPath(projectRoot, relative, "INSTALL_MARKETPLACE_PATH_INVALID").absolute;
  let marketplace = {
    name: "metis-workspace",
    interface: { displayName: "Metis Workspace Plugins" },
    plugins: []
  };
  const fileExisted = existsSync(file);
  if (fileExisted) {
    try { marketplace = JSON.parse(readFileSync(file, "utf8")); }
    catch (error) { throw new Error(`Cannot update invalid marketplace file ${relative}: ${error.message}`); }
  }
  marketplace.plugins = Array.isArray(marketplace.plugins) ? marketplace.plugins : [];
  const installedEntry = marketplaceEntry();
  const index = marketplace.plugins.findIndex((item) => item?.name === "metis");
  const currentEntry = index >= 0 ? marketplace.plugins[index] : null;
  if (currentEntry && stableStringify(currentEntry) !== stableStringify(installedEntry) && !options.force) {
    return { path: relative, status: "preserved", reason: "existing marketplace entry differs; use --force" };
  }
  if (!manifest.marketplace) {
    manifest.marketplace = {
      path: relative,
      fileCreated: !fileExisted,
      previousEntry: currentEntry,
      installedEntry
    };
  }
  if (index >= 0) marketplace.plugins[index] = installedEntry;
  else marketplace.plugins.push(installedEntry);
  if (fileExisted && stableStringify(JSON.parse(readFileSync(file, "utf8"))) === stableStringify(marketplace)) {
    return { path: relative, status: "current" };
  }
  mkdirSync(path.dirname(file), { recursive: true });
  writeFileSync(file, `${stableStringify(marketplace)}\n`, "utf8");
  return { path: relative, status: index >= 0 ? "updated" : "created" };
}

